
CREATE DATABASE DW_DistribucionHardware;
GO
USE DW_DistribucionHardware;
GO

CREATE TABLE DIM_PuestoEmp (
    ID_PUESTO  INT IDENTITY(1,1) NOT NULL,
    NOMBRE NVARCHAR(100) NOT NULL,
    CONSTRAINT PK_DIM_PuestoEmp PRIMARY KEY (ID_PUESTO)
);

CREATE TABLE DIM_DominioCorreoEmp (
    ID_DOMINIO INT IDENTITY(1,1) NOT NULL,
    NOMBRE NVARCHAR(100) NOT NULL,
    CONSTRAINT PK_DIM_DominioCorreoEmp PRIMARY KEY (ID_DOMINIO)
);

CREATE TABLE DIM_CATEGORIA (
    ID_CATEGORIA INT NOT NULL,
    CODIGO NVARCHAR(50) NOT NULL,
    NOMBRE NVARCHAR(100) NOT NULL,
    CONSTRAINT PK_DIM_CATEGORIA PRIMARY KEY (ID_CATEGORIA)
);


CREATE TABLE DIM_TIEMPO (
    ID_TIEMPO INT NOT NULL,
    SEMANA INT NOT NULL,
    TRIMESTRE INT NOT NULL,
    CUATRIMESTRE INT NOT NULL,
    DIA_SEMANA NVARCHAR(20) NOT NULL,
    NOMBRE_MES NVARCHAR(20) NOT NULL,
    CONSTRAINT PK_DIM_TIEMPO PRIMARY KEY (ID_TIEMPO)
);

CREATE TABLE DIM_EMPLEADO (
    ID_EMPLEADO INT NOT NULL,   
    ID_PUESTO INT NOT NULL,
    ID_DOMINIO INT NOT NULL,
    NOMBRE_COMPLETO NVARCHAR(150) NOT NULL,
    CONSTRAINT PK_DIM_EMPLEADO PRIMARY KEY (ID_EMPLEADO),
    CONSTRAINT FK_EMPLEADO_PUESTO  FOREIGN KEY (ID_PUESTO)
        REFERENCES DIM_PuestoEmp (ID_PUESTO),
    CONSTRAINT FK_EMPLEADO_DOMINIO FOREIGN KEY (ID_DOMINIO)
        REFERENCES DIM_DominioCorreoEmp (ID_DOMINIO)
);

CREATE TABLE DIM_PRODUCTO (
    ID_PRODUCTO  INT NOT NULL,      
    ID_CATEGORIA INT NOT NULL,
    NOMBRE NVARCHAR(255) NOT NULL,
    DESCRIPCION  NVARCHAR(2000) NULL,
    CONSTRAINT PK_DIM_PRODUCTO PRIMARY KEY (ID_PRODUCTO),
    CONSTRAINT FK_PRODUCTO_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES DIM_CATEGORIA (ID_CATEGORIA)
);

CREATE TABLE DIM_CLIENTES (
    ID_CLIENTE INT NOT NULL,
    NOMBRE_COMPLETO NVARCHAR(255) NOT NULL,
    DIRECCION NVARCHAR(255) NULL,
    CONSTRAINT PK_DIM_CLIENTES PRIMARY KEY (ID_CLIENTE)
);


CREATE TABLE HECHO_VENTAS (
    DETALLE_VENTA  INT IDENTITY(1,1) NOT NULL,
    ID_VENTA INT NOT NULL,             
    ID_TIEMPO  INT NOT NULL,
    ID_EMPLEADO INT NOT NULL,
    ID_PRODUCTO INT NOT NULL,
    ID_CLIENTE INT NOT NULL,
    CANTIDAD_VENTA INT NOT NULL,
    CONSTRAINT PK_HECHO_VENTAS PRIMARY KEY (DETALLE_VENTA),
    CONSTRAINT FK_HECHO_TIEMPO   FOREIGN KEY (ID_TIEMPO) REFERENCES DIM_TIEMPO (ID_TIEMPO),
    CONSTRAINT FK_HECHO_EMPLEADO FOREIGN KEY (ID_EMPLEADO) REFERENCES DIM_EMPLEADO (ID_EMPLEADO),
    CONSTRAINT FK_HECHO_PRODUCTO FOREIGN KEY (ID_PRODUCTO) REFERENCES DIM_PRODUCTO (ID_PRODUCTO),
    CONSTRAINT FK_HECHO_CLIENTE  FOREIGN KEY (ID_CLIENTE) REFERENCES DIM_CLIENTES (ID_CLIENTE)
);
GO
